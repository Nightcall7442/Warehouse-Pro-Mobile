/**
 * «2 заказов ожидают синхронизации» — так писала полоса поверх всех экранов.
 *
 * Форму выбирали двумя вариантами вместо трёх, и двойки-тройки-четвёрки
 * получали окончание от пяти. Первое, что видел агент, когда пропадала связь.
 */
import { describe, it, expect } from "@jest/globals";
import { plural } from "../lib/plural";

const заказ = (n: number) => `${n} ${plural(n, "заказ", "заказа", "заказов")}`;

describe("склонение по числу", () => {
  it("один — два — пять", () => {
    expect(заказ(1)).toBe("1 заказ");
    expect(заказ(2)).toBe("2 заказа");
    expect(заказ(4)).toBe("4 заказа");
    expect(заказ(5)).toBe("5 заказов");
  });

  it("одиннадцать — четырнадцать берут форму многих", () => {
    // Исключение, из-за которого правило «по последней цифре» не работает.
    for (const n of [11, 12, 13, 14]) expect(заказ(n)).toBe(`${n} заказов`);
  });

  it("десятки считаются по последней цифре", () => {
    expect(заказ(21)).toBe("21 заказ");
    expect(заказ(22)).toBe("22 заказа");
    expect(заказ(25)).toBe("25 заказов");
    expect(заказ(101)).toBe("101 заказ");
    expect(заказ(111)).toBe("111 заказов");
  });

  it("ноль — форма многих", () => {
    expect(заказ(0)).toBe("0 заказов");
  });

  it("глагол согласуется тем же правилом", () => {
    // Выходило «1 заказ ожидают отправки»: глагол не согласовывали вовсе.
    expect(plural(1, "ожидает", "ожидают", "ожидают")).toBe("ожидает");
    expect(plural(2, "ожидает", "ожидают", "ожидают")).toBe("ожидают");
  });
});
