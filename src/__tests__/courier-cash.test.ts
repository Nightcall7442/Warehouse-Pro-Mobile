/**
 * Наличные, принятые курьером, доходят до сервера числом.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Поле «Сумма наличных» на экране доставок отдавало набранную СТРОКУ прямо в
 * запрос. Русская раскладка даёт запятую, и «150,50» уходило запятой. На
 * сервере такая строка становится нулём: заказ отмечался доставленным, деньги
 * курьер взял, а в системе оплаты нет — магазину оставался долг на всю сумму.
 *
 * Ровно эта беда уже была разобрана на экране сдачи доставки, но там путь
 * спящий; живой — здесь, у курьера в списке.
 *
 * Проверяется разбор, а не разметка: именно он отделяет «взял 150 500» от
 * «взял ноль».
 */
import { describe, it, expect } from "@jest/globals";
import { parseAmount } from "../lib/order-money";

/** Что уйдёт на сервер: пусто — значит наличных не брали. */
function cashForServer(typed: string): string | undefined {
  const paid = parseAmount(typed);
  return paid > 0 ? String(paid) : undefined;
}

describe("сумма наличных курьера", () => {
  it("запятая читается как разделитель, а не теряется", () => {
    expect(cashForServer("150,50")).toBe("150.5");
  });

  it("точка тоже читается", () => {
    expect(cashForServer("150.50")).toBe("150.5");
  });

  it("пробелы из набора не мешают", () => {
    expect(cashForServer(" 150,50 ")).toBe("150.5");
  });

  it("пустое поле означает «наличных не брали»", () => {
    // Не ноль и не «0»: сервер отличает «оплаты не было» от «оплатили ноль».
    expect(cashForServer("")).toBeUndefined();
    expect(cashForServer("0")).toBeUndefined();
    expect(cashForServer(".")).toBeUndefined();
  });

  it("минус не проходит", () => {
    expect(cashForServer("-500")).toBeUndefined();
  });

  it("крупная сумма не теряет разряды", () => {
    expect(cashForServer("1250000")).toBe("1250000");
  });
});
