/**
 * Пустой список и сбой связи не должны выглядеть одинаково.
 *
 * Агент открывает приложение в подвале магазина, где связи нет. Запрос не
 * доходит, данных нет, и экран честно пишет «На сегодня визитов нет» или
 * «Заказов пока нет». Единственный разумный вывод для человека — что маршрут
 * не назначили или что за день он ничего не оформил. В первом случае он
 * уезжает, во втором — оформляет заказ повторно, хотя первый уже на сервере.
 *
 * Правильная ветка в приложении была написана — на экране доставок, с прямым
 * объяснением в комментарии. Остальные экраны её не получили.
 *
 * ── Почему проверка по исходнику ────────────────────────────────────────────
 *
 * Экран вкладки в тесте не поднять без навигации, запросов, темы и хранилища
 * сессии. Вопрос же простой и виден в коде прямо: спрашивает ли экран у
 * запроса, была ли ошибка. Границы срезов узкие — проверяется именно ветка
 * отрисовки, а не файл целиком.
 */
const fs = require("node:fs") as typeof import("node:fs");
const path = require("node:path") as typeof import("node:path");

const read = (rel: string) => fs.readFileSync(path.resolve(process.cwd(), rel), "utf8");

describe("экраны отличают «пусто» от «не загрузилось»", () => {
  it.each([
    ["app/(tabs)/index.tsx", "главная агента"],
    ["app/(tabs)/orders.tsx", "вкладка заказов"],
    ["app/(tabs)/deliveries.tsx", "вкладка доставок"],
  ])("%s (%s) читает признак ошибки запроса", (file) => {
    // isError у запроса — единственный способ отличить «данных нет» от
    // «данные не пришли»: в обоих случаях список пустой.
    expect(/isError/.test(read(file))).toBe(true);
  });

  it("на главной «нет визитов» показывается только при успешном запросе", () => {
    const src = read("app/(tabs)/index.tsx");
    const at = src.indexOf("На сегодня визитов нет");
    expect(at).toBeGreaterThan(0);

    // Ищем саму ВЕТКУ, а не упоминание имени.
    //
    // Первая версия искала подстроку "plansFailed" где угодно в файле — и
    // проходила с вырезанным условием: имя оставалось в строке, где признак
    // достают из запроса. Проверка ловила объявление, а не использование.
    // Поймал это только прогон с намеренно сломанным кодом.
    const errorBranch = src.indexOf(") : plansFailed ? (");
    expect(errorBranch).toBeGreaterThan(0);
    expect(errorBranch).toBeLessThan(at);
  });

  it("на вкладке заказов «заказов нет» зависит от признака ошибки", () => {
    const src = read("app/(tabs)/orders.tsx");
    const at = src.indexOf("Заказов пока нет");
    expect(at).toBeGreaterThan(0);

    // Смотрим на сам текст: он должен стоять в тернарнике с isError, а не
    // печататься безусловно.
    const around = src.slice(Math.max(0, at - 200), at + 40);
    expect(around).toContain("isError");
  });
});

describe("созданный заказ появляется в списке", () => {
  it("после создания списки помечаются устаревшими", () => {
    // Вкладки не размонтируются, пока сверху лежит экран нового заказа, а у
    // запроса ["myOrders"] выдержка две минуты. Без пометки агент вернётся и
    // не увидит только что созданного заказа — и оформит второй.
    const src = read("app/order/new.tsx");
    const start = src.indexOf("const createMutation");
    expect(start).toBeGreaterThan(0);

    // Узко: только тело onSuccess этой мутации. Первая версия похожей
    // проверки в веб-репозитории брала полторы тысячи знаков подряд и
    // находила имя поля в списке зависимостей — то есть не проверяла ничего.
    const onSuccess = src.indexOf("onSuccess:", start);
    const body = src.slice(onSuccess, src.indexOf("onError:", onSuccess));

    expect(body).toContain("invalidateQueries");
    expect(body).toContain("myOrders");
  });
});
