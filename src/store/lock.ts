import { create } from "zustand";

/**
 * Заблокирован ли экран после долгого простоя.
 *
 * Отдельное состояние появилось потому, что блокировку раньше делал logout():
 * любая неудача биометрии стирала токен и кэш профиля, и агент оказывался на
 * форме входа с требованием ввести пароль. Неудача же наступала не только
 * когда телефон взял чужой — хватало нажатия «Назад», отсутствия
 * зарегистрированного отпечатка или нескольких неточных касаний подряд.
 *
 * Блокировка и выход — разные вещи. Блокировка закрывает содержимое от чужих
 * глаз и снимается повторной попыткой; выход уничтожает сессию и делается
 * только по явному решению человека. Здесь живёт первое.
 */
interface LockState {
  locked: boolean;
  lock: () => void;
  unlock: () => void;
}

export const useLockStore = create<LockState>((set) => ({
  locked: false,
  lock: () => set({ locked: true }),
  unlock: () => set({ locked: false }),
}));
