import { useCallback, useRef } from "react";
import { useFocusEffect } from "expo-router";
import { useQueryClient } from "@tanstack/react-query";

/**
 * Обновить данные экрана, когда на вкладку вернулись.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Жалоба владельца звучала так: «табы не обновляются при смене табы». Причина
 * ровно одна и лежит в устройстве навигации.
 *
 * Вкладки expo-router не размонтируют экран при переключении: он остаётся
 * висеть со своими подписками. Запрос уходит один раз — при первом открытии
 * вкладки, — и больше не повторяется никогда: react-query перезапрашивает
 * устаревшее при НОВОЙ подписке, а новой не случается.
 *
 * Штатного лекарства — refetchOnWindowFocus — в телефоне нет: у приложения нет
 * окна, и без focusManager (он подключён в app/_layout.tsx) это свойство не
 * срабатывает вовсе. Оно же, кстати, чинит вторую половину беды: возвращение
 * из фона.
 *
 * Получалось так: агент оформил заказ, вернулся на «Заказы» — заказа нет;
 * курьер отметил доставку, зашёл на главную — счётчик прежний. За свежими
 * данными приходилось выгружать приложение из памяти и открывать заново.
 *
 * ── Почему ключи, а не «обновить всё» ───────────────────────────────────────
 *
 * Экраны остаются смонтированными, поэтому «обновить все действующие запросы»
 * означало бы тянуть с сервера данные всех вкладок сразу на каждое
 * переключение. У человека в поле мобильный интернет и часто 3G — платить за
 * пять чужих экранов, чтобы посмотреть один свой, нельзя.
 *
 * ── Почему первый показ пропускается ────────────────────────────────────────
 *
 * При первом открытии вкладки запрос уже уходит сам. Без пропуска экран
 * дёргал бы сервер дважды подряд на каждом первом заходе.
 */
export function useRefreshOnFocus(keys: readonly (readonly unknown[])[]): void {
  const queryClient = useQueryClient();
  const firstFocus = useRef(true);

  useFocusEffect(
    useCallback(() => {
      if (firstFocus.current) {
        firstFocus.current = false;
        return;
      }
      for (const queryKey of keys) {
        queryClient.invalidateQueries({ queryKey: queryKey as unknown[] });
      }
      // keys приходят литералом из экрана и не меняются между отрисовками;
      // сравнивать их по ссылке значило бы обновлять данные на каждый рендер.
      // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [queryClient]),
  );
}
