import { parseAmount } from "./order-money";

/**
 * Правило остатка: когда количество больше того, что есть на складе.
 *
 * ── Почему отдельно от экрана ───────────────────────────────────────────────
 *
 * Правило жило внутри app/order/new.tsx одной строкой в теле компонента, и
 * проверить его можно было только глазами на собранном приложении: файл экрана
 * тянет за собой весь expo-router. А ошибка в нём не выглядит поломкой —
 * кнопка «Далее» просто не загорается, и человек думает, что чего-то не
 * заполнил.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Со сканера в форму приходили только имя товара и цена; остатка среди них
 * нет, и строке записывали ноль. Проверка срабатывала на первой же единице:
 * заказ по отсканированному штрих-коду нельзя было оформить ВООБЩЕ никогда.
 * На экране при этом стояло «Остаток: 0» — хотя товар на складе был.
 *
 * Отсюда и различие ниже: ноль на складе — это «нельзя», а неизвестный
 * остаток — «пока не знаем», и заказу он не мешает. Настоящую нехватку всё
 * равно поймает сервер при оформлении.
 */
export interface StockLine {
  /** Остаток на складе. null — неизвестен, а не ноль. */
  available: number | null;
  quantity: string | number;
}

export function overStock(line: StockLine): boolean {
  if (line.available === null) return false;
  const qty = parseAmount(line.quantity);
  return qty > 0 && qty > line.available;
}
