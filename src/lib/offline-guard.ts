import { Alert } from "react-native";
import * as Haptics from "expo-haptics";
import { tt } from "../i18n";

/* ═══════════════════════════════════════════════════════════════════════════
   Сообщить, что запись в очередь НЕ легла на диск.

   ── Зачем это нужно ────────────────────────────────────────────────────────

   Запись в очередь возвращает признак: удалось ли дописать её на диск. На
   рабочих телефонах место кончается, и запись остаётся только в памяти —
   до первой выгрузки приложения системой. Происходит она сама, пока телефон
   лежит в кармане.

   Курьерский поток этот признак не читал и в любом случае рапортовал
   «сохранено офлайн». Курьер отдавал товар, брал деньги, видел спокойное
   сообщение и уходил. Отметки не оставалось нигде: ни на сервере, ни на
   диске. Деньги в кармане, в системе — ничего.

   ── Почему модальное окно, а не всплывающее сообщение ──────────────────────

   Всплывающее затирается следующим, и на этих экранах следующее приходит
   сразу: обновление списка, отклик о завершении действия. Окно нужно закрыть
   рукой — значит его прочитают. Так же сделано в оформлении заказа.
   ═══════════════════════════════════════════════════════════════════════════ */

/**
 * @param what Что именно не сохранилось, в именительном падеже и уже на языке
 *             телефона: t("Отметка о доставке", "Yetkazish belgisi").
 */
export function reportNotQueued(what: string) {
  void Haptics.notificationAsync(Haptics.NotificationFeedbackType.Error);
  Alert.alert(
    tt(`${what} НЕ сохранена`, `${what} SAQLANMADI`),
    tt("На телефоне нет места, и запись не легла на диск — она держится только в памяти и пропадёт, когда приложение выгрузится.\n\nОсвободите место и повторите действие. Если товар уже отдан или деньги приняты — сообщите в офис прямо сейчас, чтобы отметку поставили вручную.",
      "Telefonda joy yo'q, yozuv diskka tushmadi — u faqat xotirada turibdi va ilova yopilganda yo'qoladi.\n\nJoy bo'shatib, amalni qaytaring. Agar tovar berilgan yoki pul olingan bo'lsa — hoziroq ofisga xabar bering, belgini qo'lda qo'yishsin."),
  );
}
