import { Image } from "react-native";
import { ImageManipulator, SaveFormat } from "expo-image-manipulator";
import { tt } from "../i18n";
import { humanError } from "./error-text";

/**
 * Подготовить снимок к отправке: уменьшить и сжать.
 *
 * ── Почему это нужно ────────────────────────────────────────────────────────
 *
 * `quality` в выборе изображения меняет степень сжатия, но НЕ разрешение.
 * Снимок с сорокавосьмимегапиксельной камеры остаётся снимком в полное
 * разрешение: JPEG около 2.5 МБ, а base64 раздувает его ещё на треть — до
 * ~3.4 МБ. Клиентский лимит 3.5 МБ, то есть часть кадров упирается в него и
 * получает отказ, а совет «снимите заново» невыполним: пересъёмка даёт тот же
 * размер.
 *
 * Даже те, что проходят, обходятся дорого. Мерчандайзер снимает полку пять раз
 * за визит — это ~17 МБ по сельскому 3G, с таймаутом на каждую загрузку. И вся
 * строка base64 живёт в памяти вкладки целиком, вместе с копией в data-URL;
 * на недорогом Android это реальный риск падения по памяти.
 *
 * ── Что выбрано и почему ────────────────────────────────────────────────────
 *
 * 1600 px по длинной стороне: фотографии здесь — доказательство визита и вид
 * витрины, их смотрят на телефоне и в веб-панели. Разглядеть ценник этого
 * хватает с запасом, а разница в объёме — на порядок.
 *
 * Уменьшение делается ДО сжатия: сжимать полноразмерный кадр, чтобы потом его
 * уменьшить, — это та же работа, только дороже.
 *
 * ── Почему сторона выбирается, а не задаётся всегда ширина ──────────────────
 *
 * Здесь стояло `resize({ width: 1600 })` без оглядки на сам кадр, и это делало
 * не то, что написано выше.
 *
 * Вертикальный снимок 3000×4000 — а полку и витрину снимают именно вертикально —
 * превращался в 1600×2133. Длинная сторона выходила 2133, то есть на треть
 * больше задуманного, и файл соответственно тяжелее.
 *
 * Хуже другое: `resize` не только уменьшает. Кадр 800×600 — уже маленький,
 * пришедший из галереи или со старого телефона — РАСТЯГИВАЛСЯ до 1600×1200.
 * Подготовка к отправке увеличивала файл вместо того, чтобы его уменьшить, и
 * ровно на медленной связи, ради которой всё и делается.
 *
 * Теперь сторона выбирается по кадру, а снимок меньше предела не трогается
 * вовсе.
 */

/** Длинная сторона после уменьшения. */
const MAX_SIDE = 1600;

/** Степень сжатия JPEG. 0.7 — заметно легче, чем 0.9, и без видимых артефактов. */
const QUALITY = 0.7;

export interface PreparedPhoto {
  /** Готовая строка для отправки: data:image/jpeg;base64,… */
  dataUrl: string;
  /** Размер в байтах — для диагностики и сообщений пользователю. */
  bytes: number;
}

/**
 * Размеры кадра по его адресу.
 *
 * Image.getSize читает заголовок файла и не декодирует картинку целиком —
 * поэтому спросить размер дешевле, чем отрисовать кадр ради него.
 *
 * Отказ не считается бедой: не узнали размер — уменьшаем по ширине, как было
 * раньше. Это хуже, чем по длинной стороне, но лучше, чем не отправить фото
 * вовсе из-за того, что не смогли прочитать заголовок.
 */
async function imageSize(uri: string): Promise<{ width: number; height: number } | null> {
  return new Promise(resolve => {
    Image.getSize(
      uri,
      (width, height) => resolve(width > 0 && height > 0 ? { width, height } : null),
      () => resolve(null),
    );
  });
}

/**
 * Принимает URI снимка (из камеры или галереи), возвращает готовый data-URL.
 *
 * URI, а не base64: просить у камеры base64 значит держать в памяти лишнюю
 * копию полноразмерного кадра ровно до того момента, как мы его уменьшим.
 */
export async function preparePhoto(uri: string): Promise<PreparedPhoto> {
  const size = await imageSize(uri);
  const image = ImageManipulator.manipulate(uri);

  if (!size) {
    image.resize({ width: MAX_SIDE });
  } else if (Math.max(size.width, size.height) > MAX_SIDE) {
    // Одна сторона, а не обе: вторую `resize` досчитает сам и сохранит
    // пропорции. Указать обе значило бы растянуть кадр.
    image.resize(size.width >= size.height ? { width: MAX_SIDE } : { height: MAX_SIDE });
  }

  const rendered = await image.renderAsync();
  const result = await rendered.saveAsync({
    compress: QUALITY,
    format: SaveFormat.JPEG,
    base64: true,
  });

  if (!result.base64) {
    throw humanError(tt("Не удалось подготовить фото к отправке", "Rasmni yuborishga tayyorlab bo'lmadi"));
  }

  return {
    dataUrl: `data:image/jpeg;base64,${result.base64}`,
    // Каждый символ base64 несёт 6 бит, то есть 4 символа на 3 байта.
    bytes: Math.floor((result.base64.length * 3) / 4),
  };
}
