/**
 * Какие вкладки видит роль.
 *
 * Правило жило внутри CustomTabBar, и проверить его можно было только глазами
 * на собранном APK. Здесь оно отдельной функцией — потому что ошибка в нём не
 * выглядит поломкой: экран остаётся в приложении, просто до него нечем дойти.
 *
 * Так и вышло со «Слежением»: экран с картой агентов лежал в ALWAYS_HIDDEN, и
 * единственной дверью к нему была карточка «ТРЕКИНГ» на главной. Супервайзеры
 * карту не находили.
 */

/** Экраны, до которых ходят из других мест, а не с панели вкладок. */
export const ALWAYS_HIDDEN = ["gps", "barcode", "plan", "deliveries"];

export type Role = "ceo" | "operator" | "supervisor" | "agent" | "merchandiser" | "courier";

/** Роли, которые смотрят за чужой работой: у них своя главная и свои экраны. */
export function isOversight(role: string | undefined): boolean {
  return role === "supervisor" || role === "ceo" || role === "operator";
}

/** Кому сервер отдаёт местоположения агентов (agent.getLocations). */
export function canSeeAgentMap(role: string | undefined): boolean {
  return role === "ceo" || role === "supervisor";
}

export function isTabVisible(name: string, role: string | undefined): boolean {
  /*
    Исключение из списка скрытых: план визитов мерчендайзеру.

    Мерчендайзер видел ровно две вкладки — «Главная» и «Магазины», — а его
    работа, отчёт о визите, открывается только с экрана плана. Дверь туда
    была одна: стрелка в углу карточки «План на сегодня» на главной. Основная
    работа роли не должна прятаться за стрелкой размером с иконку.

    Агенту вкладку не даём намеренно: у него их и так пять, а план он видит
    той же карточкой на главной, где рядом лежат каталог и заказы.
  */
  if (name === "plan" && role === "merchandiser") return true;

  /*
    То же для курьера: доставки — его работа, и они были скрыты.

    У курьера оставалась ровно ОДНА вкладка, «Главная», — панель из одной
    кнопки, которая ничего не переключает. А экран доставок, ради которого
    он и открывает приложение, лежал в списке всегда скрытых: дойти до него
    можно было только плиткой с главной.
  */
  if (name === "deliveries" && role === "courier") return true;

  if (ALWAYS_HIDDEN.includes(name)) return false;

  const oversight = isOversight(role);
  const courier = role === "courier";
  const merchandiser = role === "merchandiser";

  // Своя работа агента: каталог, его заказы, его профиль.
  /*
    Профиль — тем, у кого панель иначе почти пуста.

    У курьера и мерчендайзера вкладок одна-две, и выход из учётной записи им
    приходилось искать плиткой на главной. У надзорных ролей панель полная
    (главная, магазины, планы, нормы) — им профиль в неё не добавляем, чтобы
    не тесниться: решение прежнее и намеренное.
  */
  if (name === "profile" && (courier || merchandiser)) return true;

  // Своя работа агента: каталог, его заказы, его профиль.
  if (name === "catalog" || name === "orders" || name === "profile") {
    return !oversight && !courier && !merchandiser;
  }

  /*
    Карта агентов — только тем, кому её отдаёт сервер.

    agent.getLocations стоит на supervisorQuery, а это ceo и супервайзер;
    оператор в надзорные роли входит, но этот запрос получит отказом. Вкладка,
    открывающая экран с ошибкой, хуже отсутствующей.
  */
  if (name === "tracking") return canSeeAgentMap(role);

  // Надзорные экраны: планы визитов и нормы.
  if (name === "plans" || name === "targets") return oversight;

  // Магазины — всем, кроме курьера: он едет по заказам, а не по точкам.
  if (name === "shops") return !courier;

  return true;
}
