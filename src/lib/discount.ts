/**
 * Скидка — процент, от 0 до 100.
 *
 * Верхней границы в полях не было: набрать можно было и 150. Дальше
 * происходило вот что.
 *
 * На экране строка заказа со скидкой 150 показывала ОТРИЦАТЕЛЬНУЮ сумму —
 * `цена × количество × (1 − 150/100)`. Агент видел минус там, где ждал
 * стоимость.
 *
 * Отправить такой заказ всё равно не выходило: сервер режет диапазон 0–100 в
 * двух местах и отвечает отказом. Но узнавал об этом агент в самом конце, уже
 * заполнив магазин, товары и количества, — и без внятного указания, какая
 * именно строка виновата.
 *
 * Поэтому граница ставится там же, где набирают: сразу видно, что больше ста
 * не бывает.
 *
 * ── Чего здесь нет ─────────────────────────────────────────────────────────
 *
 * Порога, выше которого скидку должен подтверждать супервайзер. Сто процентов
 * сервер принимает: заказ уходит на ноль, товар при этом резервируется и
 * списывается со склада. Нужен ли такой порог и с какой цифры — это решение о
 * том, как ведут дела, а не недостаток кода, и принимать его за владельца
 * нельзя.
 */
export function clampDiscountText(raw: string): string {
  const text = raw.replace(",", ".");

  // Пустое поле и одинокая точка — промежуточные состояния набора, их нельзя
  // ни отвергать, ни превращать в ноль: иначе точку не поставить.
  if (text === "" || text === ".") return text;

  const value = Number(text);
  if (!Number.isFinite(value)) return "";
  if (value < 0) return "0";
  if (value > 100) return "100";

  return text;
}
