/**
 * Русское склонение по числу.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Форму выбирали двумя вариантами: «один — и всё остальное». Полоса поверх всех
 * экранов писала «2 заказов ожидают синхронизации», список неотправленных —
 * «2 действий». Двойки, тройки и четвёрки получали форму от пяти.
 *
 * Заодно ломалось согласование глагола: при одной записи выходило
 * «1 заказ ожидают синхронизации».
 *
 * Форм в русском три, и правило простое: 11–14 — всегда «многих» (одиннадцать
 * заказов), иначе смотрим на последнюю цифру.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = Math.abs(n) % 100;
  const mod10 = mod100 % 10;
  if (mod100 >= 11 && mod100 <= 14) return many;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}
