import * as Location from "expo-location";
import * as Battery from "expo-battery";
import { saveLocation } from "../api";

/**
 * Точка агента в момент отметки визита.
 *
 * ── Зачем ────────────────────────────────────────────────────────────────────
 *
 * Экран слежения у директора и супервайзера рисуется по agent_locations, и
 * писал в них только фоновый сбор да отдельная вкладка «GPS», которую агент
 * жмёт сам. То есть у агента с выключенным фоновым сбором визит отмечался, а
 * на карте не появлялось ничего: ни точки, ни маршрута. Начальник видел
 * «визитов сегодня: 12» и пустую карту и не мог сказать, где эти двенадцать
 * были.
 *
 * Хуже, что от этих же точек зависит проверка на подлог (api/services/
 * anti-fraud.ts): она сверяет расстояние до магазина по точкам за день. Нет
 * точек — сверять нечего, и отметка «был у магазина» ничем не подтверждена.
 *
 * Теперь каждая отметка визита сама шлёт точку: и без фото, и с фотоотчётом, и
 * из отчёта мерчандайзера.
 *
 * ── Почему ничего не ломает, если GPS выключен ──────────────────────────────
 *
 * Визит важнее точки. Отметка уже ушла на сервер к моменту вызова, и этот
 * вызов не должен ни задерживать её, ни отменять: агент в подвале магазина без
 * сигнала обязан суметь закрыть визит.
 *
 * Поэтому здесь нет ни одного throw, а ожидание ограничено десятью секундами:
 * дольше человек уже смотрит на «крутилку» и думает, что приложение зависло.
 * Разрешение НЕ запрашивается — только читается: всплывающий запрос доступа
 * поверх только что отмеченного визита выглядит как сбой, а согласие берут на
 * вкладке «GPS» и при первом запуске.
 */

/** Дольше этого не ждём: визит уже отмечен, точка — дополнение к нему. */
const FIX_TIMEOUT_MS = 10_000;

export async function sendVisitPing(): Promise<void> {
  try {
    // Только чтение разрешения: спрашивать его здесь — значит показать
    // системное окно поверх свежеотмеченного визита.
    const { status } = await Location.getForegroundPermissionsAsync();
    if (status !== "granted") return;

    const [pos, battery] = await Promise.all([
      Promise.race([
        Location.getCurrentPositionAsync({ accuracy: Location.Accuracy.Balanced }),
        new Promise<never>((_, reject) =>
          setTimeout(() => reject(new Error("GPS timeout")), FIX_TIMEOUT_MS)),
      ]),
      Battery.getBatteryLevelAsync().catch(() => null),
    ]);

    await saveLocation(
      pos.coords.latitude,
      pos.coords.longitude,
      pos.coords.accuracy ?? undefined,
      battery !== null ? Math.round(battery * 100) : undefined,
      // Время съёмки: точка, пролежавшая без связи, должна встать на карту
      // туда, где агент БЫЛ, а не туда, где телефон дозвонился.
      new Date().toISOString(),
    );
  } catch {
    /*
      Молчание намеренное, и это единственное место, где оно уместно.

      Визит уже отмечен и виден агенту. Сообщать ему «точка не ушла» значит
      тревожить за то, чего он не может исправить стоя в магазине, и делать
      это поверх успешного действия. Отсутствие точки видно там, где оно
      что-то значит, — на карте у начальника.
    */
  }
}
