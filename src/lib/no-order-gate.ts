import type { Plan } from "../api";
import { isOwnedBy, resolveShopId, type OfflineOrder } from "../store/offline";

/*
  Был ли у визита заказ — тогда причину «без заказа» не спрашиваем.

  ── Что было ────────────────────────────────────────────────────────────────

  Агент жал «Готово», визит закрывался — и всё. Директор видел двадцать
  визитов и восемь заказов, но не знал, что за остальными двенадцатью:
  «закрыто», «нет денег», «есть остаток» и «берёт у конкурента» — разные
  разговоры, и без причины ни один не начинался. Веб (PR #155) уже
  спрашивает причину; телефон закрывал визит молча.

  ── Правило ─────────────────────────────────────────────────────────────────

  Заказ есть, если:
    • сервер так сказал (agent.getPlans → hasOrder: заказ этого агента этому
      магазину в день плана), или
    • заказ этому магазину лежит в очереди телефона и ждёт связи — агент его
      оформил, просто он ещё не дошёл. Спрашивать «почему без заказа» у того,
      кто только что заказ оформил, — ровно то, за что приложение бросают.

  Из очереди считается только своё (сменный телефон: заказ агента А — не
  заказ агента Б), не отвергнутое сервером (отказ по существу — заказа нет)
  и сегодняшнее: оба экрана с кнопкой «Готово» показывают планы на сегодня.
  День плана с сервера здесь не берётся: дата может прийти полночью ISO, и
  при сдвиге часовых поясов её первые десять знаков укажут на вчера.
*/

/** Местный день «ГГГГ-ММ-ДД» — тот, в котором агент оформлял заказ. */
function localDay(d: Date): string {
  const p = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function visitHasOrder(
  plan: Pick<Plan, "hasOrder" | "shopId">,
  queuedOrders: OfflineOrder[],
  userId: number | null | undefined,
  now: Date = new Date(),
): boolean {
  if (plan.hasOrder) return true;
  if (plan.shopId == null) return false;
  const today = localDay(now);
  return queuedOrders.some(o =>
    !o.synced
    && o.retryable !== false
    && isOwnedBy(o, userId)
    && resolveShopId(o.input.shopId) === plan.shopId
    && localDay(new Date(o.createdAt)) === today,
  );
}
