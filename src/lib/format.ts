/**
 * Числа, которые агент читает вслух владельцу магазина.
 *
 * MySQL отдаёт DECIMAL строкой: остаток «1250.000», вес «12.500». Напечатанные
 * как есть, они выглядят как ошибка системы — «1250.000 кг» вместо «1250 кг».
 * Агент у полки читает это владельцу, и три нуля после запятой каждый раз
 * приходится проговаривать или пропускать.
 */

/**
 * Количество товара: без хвостовых нулей, с разделителями разрядов.
 *
 *     "1250.000" → "1 250"
 *     "12.500"   → "12,5"
 *     "0.750"    → "0,75"
 */
export function qty(value: string | number | null | undefined): string {
  if (value === null || value === undefined || value === "") return "0";
  const n = typeof value === "number" ? value : Number(value);
  // Не число — отдаём как пришло: подпись вроде «нет данных» портить нельзя.
  if (!Number.isFinite(n)) return String(value);
  // Три знака — предел точности склада (DECIMAL(15,3)), но хвостовые нули
  // не печатаются: «1250», а не «1250,000».
  return n.toLocaleString("ru", { maximumFractionDigits: 3 });
}
