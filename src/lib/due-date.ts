/**
 * Дата обещанной доплаты — из того, что курьер набрал руками.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Поле «Когда обещал доплатить» — обычный ввод с подсказкой «ГГГГ-ММ-ДД»: ни
 * маски, ни проверки. Сервер же принимает строго `^\d{4}-\d{2}-\d{2}$`
 * (api/courier-router.ts). Курьер пишет «15.09.2026», как дату пишут у нас, и
 * получает отказ — уже после того, как отдал товар и взял часть денег. Без
 * сети отметка уходит в очередь, отказ приходит позже, а в списке
 * неотправленных текст ошибки не показывается: остаётся кнопка «Повтор»,
 * которая отправит ту же самую дату.
 *
 * ── Что делаем ──────────────────────────────────────────────────────────────
 *
 * Выбор даты календарём потребовал бы новой зависимости, поэтому принимаем
 * привычный «15.09.2026» и приводим сами. Разбираем три числа в любом из двух
 * порядков: если первое четырёхзначное — это уже ISO, иначе день-месяц-год.
 * Разделитель любой (точка, дробь, дефис, пробел) — курьер набирает как
 * привык.
 *
 * Проверка отдана date-fns, а не регулярному выражению: «31.02.2026» подходит
 * под любой шаблон вида ДД.ММ.ГГГГ, но такой даты не существует, и сервер
 * примет её молча.
 */
import { parse, isValid, format } from "date-fns";

/**
 * Возвращает дату в виде «ГГГГ-ММ-ДД» или null, если разобрать не удалось.
 * Пустая строка — это не ошибка, а «дату не назвали»: тоже null, проверять
 * заполненность полю, а не разбору.
 */
export function parseDueDate(text: string | null | undefined): string | null {
  const parts = String(text ?? "").match(/\d+/g);
  if (!parts || parts.length !== 3) return null;

  const [a, b, c] = parts;
  const [y, m, d] = a.length === 4 ? [a, b, c] : [c, b, a];
  if (y.length !== 4) return null;

  const iso = `${y}-${m.padStart(2, "0")}-${d.padStart(2, "0")}`;
  const parsed = parse(iso, "yyyy-MM-dd", new Date());
  return isValid(parsed) ? format(parsed, "yyyy-MM-dd") : null;
}
